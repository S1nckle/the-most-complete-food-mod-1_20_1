package net.shawdy.themostcompletefoodmod.diet;

public class DietValuesHolder {
    private float proteins;
    private float fats;
    private float carbohydrates;
    private float fiber;
    private float minerals;
    private float vitamins;
    private float water;

    public float getProteins() {
        return proteins;
    }
    public float getFats() {
        return fats;
    }
    public float getCarbohydrates() {
        return carbohydrates;
    }
    public float getFiber() {
        return fiber;
    }
    public float getMinerals() {
        return minerals;
    }
    public float getVitamins() {
        return this.vitamins;
    }
    public float getWater() {
        return water;
    }

    public void setProteins(float proteins) {
        this.proteins = proteins;
    }
    public void setFats(float fats) {
        this.fats = fats;
    }
    public void setCarbohydrates(float carbohydrates) {
        this.carbohydrates = carbohydrates;
    }
    public void setFiber(float fiber) {
        this.fiber = fiber;
    }
    public void setMinerals(float minerals) {
        this.minerals = minerals;
    }
    public void setVitamins(float vitamins) {
        this.vitamins = vitamins;
    }
    public void setWater(float water) {
        this.water = water;
    }

}
